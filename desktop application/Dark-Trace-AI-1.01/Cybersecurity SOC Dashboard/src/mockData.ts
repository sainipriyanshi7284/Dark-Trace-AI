/**
 * Generates classification.csv content according to Day 2 Brief:
 * Columns: record_id, predicted_class, anomaly_score, evidence_status
 */
export function generateClassificationCsv(records: ReplayFlowRecord[] = REPLAY_RECORDS): string {
  const header = 'record_id,predicted_class,anomaly_score,evidence_status'
  const rows = records.map(
    (r) =>
      `${r.record_id},${r.a1_predicted_class},${r.a2_anomaly_score.toFixed(4)},${r.evidence_status}`
  )
  return [header, ...rows].join('\n')
}

/**
 * Generates policy.csv content according to Day 2 Brief:
 * Columns: policy_id, activated_after_record_id, scope_type, scope_value, expires_after_record_id, policy_action
 */
export function generatePolicyCsv(policies: DefensePolicy[] = INITIAL_POLICIES): string {
  const header =
    'policy_id,activated_after_record_id,scope_type,scope_value,expires_after_record_id,policy_action'
  const rows = policies.map(
    (p) =>
      `${p.policy_id},${p.activated_after_record_id},${p.scope_type},${p.scope_value},${p.expires_after_record_id},${p.policy_action}`
  )
  return [header, ...rows].join('\n')
}

/**
 * Generates replay.csv content according to Day 2 Brief:
 * "Use organizer-provided record IDs. For the scored interface, scope_type = SOURCE_IP, policy_action = BLOCK,
 * and action = ALLOW or BLOCK. Policies apply only to later matching records while active.
 * A BLOCK must reference a valid applicable policy; ALLOW has an empty applied_policy_id.
 * Include every test record exactly once in classification.csv and replay.csv."
 * Columns: record_id,action,applied_policy_id
 */
export function generateReplayCsv(records: ReplayFlowRecord[] = REPLAY_RECORDS): string {
  const header = 'record_id,action,applied_policy_id'
  const rows = records.map((r) => `${r.record_id},${r.final_action},${r.applied_policy_id || ''}`)
  return [header, ...rows].join('\n')
}

export function downloadCsvFile(filename: string, content: string) {
  const blob = new Blob([content], { type: 'text/csv;charset=utf-8;' })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.setAttribute('href', url)
  link.setAttribute('download', filename)
  link.style.visibility = 'hidden'
  document.body.appendChild(link)
  link.click()
  document.body.removeChild(link)
  URL.revokeObjectURL(url)
}

