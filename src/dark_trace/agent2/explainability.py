"""Statistical explainability engine for Isolation Forest network anomaly detection.

This module provides defensible, statistical feature-attribution evidence by comparing
observed network flow metrics against the baseline training distribution.

CRITICAL CYBERSECURITY & ML GOVERNANCE RULES:
1. Isolation Forest anomaly scores are statistical outlier distances, NOT calibrated probabilities.
2. Isolation Forest does NOT natively provide causal per-sample feature attribution.
3. Feature deviations generated by this engine are strictly supporting statistical evidence
   indicating which observed features are unusual relative to the baseline training distribution.
4. They must NEVER be described as proven or causal attack mechanisms.
"""

from dataclasses import dataclass
import math
from typing import Any, Dict, List, Optional, Sequence, Union

from dark_trace.agent2.preprocessor import AnomalyPreprocessor
from dark_trace.common.schemas import NetworkFlow, SupportingFeature


@dataclass
class FeatureDeviation:
    """Detailed statistical deviation metric for an individual flow feature."""

    feature_name: str
    observed_value: float
    baseline_median: float
    baseline_std: float
    signed_deviation: float
    normalized_deviation: float  # z-score-like robust magnitude
    deviation_direction: str  # HIGH | LOW | NORMAL

    def to_supporting_feature(self) -> SupportingFeature:
        """Convert into standard SupportingFeature schema object."""
        return SupportingFeature(
            feature_name=self.feature_name,
            observed_value=self.observed_value,
            baseline_median=self.baseline_median,
            deviation_direction=self.deviation_direction,
        )


class AnomalyExplainer:
    """Explains Isolation Forest anomaly detections using statistical deviation analysis.

    Compares observed flow features with the baseline reference distribution learned
    by the AnomalyPreprocessor during offline training.
    """

    def __init__(
        self,
        baseline_stats: Optional[Dict[str, Dict[str, float]]] = None,
        deviation_threshold: float = 1.5,
        max_supporting_features: int = 5,
    ):
        """Initialize the explainability engine.

        Args:
            baseline_stats: Dictionary mapping feature names to summary statistics
                (e.g., {'median': float, 'std': float, 'min': float, 'max': float}).
                Typically obtained from preprocessor.feature_stats_.
            deviation_threshold: Minimum normalized deviation magnitude required
                for a feature to be considered a significant supporting indicator.
            max_supporting_features: Maximum number of top deviating features to include.
        """
        self.baseline_stats = baseline_stats or {}
        self.deviation_threshold = max(0.1, float(deviation_threshold))
        self.max_supporting_features = max(1, int(max_supporting_features))

    def update_baseline_stats(self, stats: Dict[str, Dict[str, float]]) -> None:
        """Update or refresh the reference baseline statistics."""
        self.baseline_stats = dict(stats)

    def explain_flow(
        self,
        record: Union[NetworkFlow, Dict[str, Any]],
        preprocessor: Optional[AnomalyPreprocessor] = None,
    ) -> List[SupportingFeature]:
        """Analyze a network flow and return the top supporting unusual features.

        Args:
            record: NetworkFlow instance or raw dictionary.
            preprocessor: Optional fitted AnomalyPreprocessor. If provided, its
                feature_stats_ and feature_names_ will be utilized if baseline_stats
                is not explicitly set.

        Returns:
            List[SupportingFeature]: Top deviating features sorted by deviation magnitude.
        """
        # Resolve reference statistics
        stats_ref = self.baseline_stats
        if not stats_ref and preprocessor is not None and getattr(preprocessor, "feature_stats_", None):
            stats_ref = preprocessor.feature_stats_

        # Extract numerical features from record
        if isinstance(record, NetworkFlow):
            raw_features = dict(record.features)
        elif isinstance(record, dict):
            raw_features = {}
            if "features" in record and isinstance(record["features"], dict):
                raw_features.update(record["features"])
            for k, v in record.items():
                if k != "features":
                    raw_features[k] = v
        else:
            return []

        deviations: List[FeatureDeviation] = []

        for feature_name, val in raw_features.items():
            if val is None:
                continue

            try:
                f_val = float(val)
            except (TypeError, ValueError):
                continue

            if math.isnan(f_val) or math.isinf(f_val):
                continue

            # Look up baseline reference statistics for this feature
            col_stats = stats_ref.get(feature_name, {})
            median_val = col_stats.get("median", 0.0)
            std_val = col_stats.get("std", 0.0)

            # Robust dispersion guard against zero or near-zero variance
            if std_val < 1e-6:
                # Use 10% of median or 1.0 as fallback scale to avoid division by zero
                dispersion = max(1e-6, abs(median_val) * 0.1, 1.0)
            else:
                dispersion = std_val

            signed_dev = f_val - median_val
            norm_dev = abs(signed_dev) / dispersion

            if signed_dev > 1e-6:
                direction = "HIGH"
            elif signed_dev < -1e-6:
                direction = "LOW"
            else:
                direction = "NORMAL"

            # Filter features that exhibit notable statistical deviation
            if norm_dev >= self.deviation_threshold or not stats_ref:
                deviations.append(
                    FeatureDeviation(
                        feature_name=feature_name,
                        observed_value=f_val,
                        baseline_median=median_val,
                        baseline_std=std_val,
                        signed_deviation=signed_dev,
                        normalized_deviation=norm_dev,
                        deviation_direction=direction,
                    )
                )

        # Sort features by absolute normalized deviation in descending order
        deviations.sort(key=lambda d: d.normalized_deviation, reverse=True)

        # Limit to top max_supporting_features
        top_deviations = deviations[: self.max_supporting_features]

        return [d.to_supporting_feature() for d in top_deviations]

    def generate_narrative_explanation(
        self,
        supporting_features: Sequence[SupportingFeature],
        is_anomaly: bool,
        raw_anomaly_score: float,
        normalized_anomaly_score: float,
    ) -> str:
        """Generate a concise, human-readable statistical explanation narrative.

        Args:
            supporting_features: Identified top deviating features.
            is_anomaly: Anomaly classification result.
            raw_anomaly_score: Decision function score.
            normalized_anomaly_score: Outlier severity index [0.0, 1.0].

        Returns:
            str: Explanatory summary suitable for SOC analysts and Agent 3 context.
        """
        if not is_anomaly:
            return (
                f"Traffic flow exhibited normal statistical characteristics "
                f"(severity index: {normalized_anomaly_score:.2f}, raw score: {raw_anomaly_score:.3f}). "
                f"No significant feature deviations detected relative to baseline profile."
            )

        if not supporting_features:
            return (
                f"Traffic flow flagged as anomalous (severity index: {normalized_anomaly_score:.2f}, "
                f"raw score: {raw_anomaly_score:.3f}). Subtle multi-dimensional cluster divergence "
                f"without individual extreme single-feature deviations."
            )

        bullet_points = []
        for feat in supporting_features:
            if feat.baseline_median is not None and abs(feat.baseline_median) > 1e-6:
                ratio = feat.observed_value / feat.baseline_median
                bullet_points.append(
                    f"{feat.feature_name} ({feat.deviation_direction}: observed {feat.observed_value:,.2f} "
                    f"vs baseline median {feat.baseline_median:,.2f}, {ratio:.1f}x)"
                )
            else:
                bullet_points.append(
                    f"{feat.feature_name} ({feat.deviation_direction}: observed {feat.observed_value:,.2f})"
                )

        features_str = "; ".join(bullet_points)
        return (
            f"Anomalous traffic pattern detected (severity index: {normalized_anomaly_score:.2f}, "
            f"raw score: {raw_anomaly_score:.3f}). Supporting feature deviations: {features_str}. "
            f"Note: Deviations indicate statistical divergence, not confirmed causality."
        )
