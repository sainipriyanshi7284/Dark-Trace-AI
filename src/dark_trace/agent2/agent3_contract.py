"""Agent 3 Evidence Fusion Integration Contract and Payload Formatter.

This module establishes the formal integration interface between Agent 2
(Intelligent Anomaly Detection & Threat Intelligence) and Agent 3 (Evidence Fusion).

ARCHITECTURE CONTRACT:
- Agent 1: Supervised threat classification (e.g. predicted_class, classifier_confidence).
- Agent 2: Unsupervised statistical anomaly detection (severity index, supporting features)
  and external threat intelligence enrichment (TinyFish findings, sources).
- Agent 3: Evidence fusion engine that combines Agent 1 and Agent 2 evidence to formulate
  the final composite risk assessment and mitigation recommendation.

MANDATORY INDEPENDENCE RULE:
- Agent 2 operates independently of Agent 1.
- Agent 2 NEVER ingests or requires Agent 1's outputs.
- If Agent 1 is offline or delayed, Agent 2 evidence remains 100% valid and consumable by Agent 3.
- If Agent 2 is offline, Agent 1 evidence remains 100% valid and consumable by Agent 3.
"""

from typing import Any, Dict, Optional

from dark_trace.common.schemas import Agent2Evidence


def format_agent2_for_agent3(evidence: Agent2Evidence) -> Dict[str, Any]:
    """Format Agent2Evidence into a structured schema specifically prepared for Agent 3 fusion.

    Args:
        evidence: Agent2Evidence payload generated by Agent 2.

    Returns:
        Dict[str, Any]: Standardized evidence package containing:
            - agent_id: 'A2'
            - flow_id: Flow identifier for cross-agent correlation
            - timestamp: Evidence generation timestamp
            - anomaly_evidence: ML outlier classification, scores, and top features
            - threat_intelligence: External contextual findings and attribution
            - routing_metadata: Source/destination IPs, ports, and protocol
    """
    ev_dict = evidence.to_dict()

    return {
        "agent_id": "A2",
        "flow_id": evidence.flow_id,
        "timestamp": evidence.timestamp,
        "anomaly_evidence": {
            "is_anomaly": evidence.anomaly_detection.is_anomaly,
            "anomaly_label": evidence.anomaly_detection.anomaly_label,
            "anomaly_score": evidence.anomaly_detection.normalized_anomaly_score,
            "raw_score": evidence.anomaly_detection.raw_anomaly_score,
            "decision_threshold": evidence.anomaly_detection.threshold,
            "model_version": evidence.anomaly_detection.model_version,
            "supporting_features": [
                f.to_dict() if hasattr(f, "to_dict") else f
                for f in evidence.anomaly_detection.supporting_features
            ],
            "inference_latency_ms": evidence.anomaly_detection.inference_latency_ms,
        },
        "threat_intelligence": ev_dict.get("threat_intelligence", {}),
        "routing_metadata": dict(evidence.metadata),
    }


def create_agent3_composite_handover(
    flow_id: str,
    agent2_evidence: Optional[Agent2Evidence] = None,
    agent1_evidence: Optional[Dict[str, Any]] = None,
) -> Dict[str, Any]:
    """Demonstrate composite multi-agent evidence handover to Agent 3.

    Proves architectural independence: Agent 3 can receive either agent's evidence
    alone or both simultaneously.

    Args:
        flow_id: Unique flow identifier.
        agent2_evidence: Optional Agent 2 evidence.
        agent1_evidence: Optional Agent 1 evidence.

    Returns:
        Dict[str, Any]: Handover bundle ready for Agent 3 fusion logic.
    """
    a2_payload = format_agent2_for_agent3(agent2_evidence) if agent2_evidence else None

    return {
        "flow_id": flow_id,
        "agent1_available": agent1_evidence is not None,
        "agent2_available": a2_payload is not None,
        "agent1_evidence": agent1_evidence,
        "agent2_evidence": a2_payload,
    }
